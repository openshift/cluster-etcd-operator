func createCertForNode(description, secretName, certName string, node *corev1.Node,
	secretInformer corev1informers.SecretInformer,
	secretGetter corev1client.SecretsGetter,
	recorder events.Recorder,
	certValidity CertValidity,
	pkiProvider pki.PKIProfileProvider,
) (*certrotation.RotatedSelfSignedCertKeySecret, error) {
	ipAddresses, err := dnshelpers.GetInternalIPAddressesForNodeName(node)
	if err != nil {
		return nil, fmt.Errorf("could not retrieve internal IP addresses for node: %w", err)
	}
	hostNames := getServerHostNames(ipAddresses)

	// MakeServerCertForDuration sorts hostnames (via sets.List) before
	// choosing the first as Subject CN. UserInfo.Name must equal that
	// value or cert generation aborts.
	// Sort so hostNames[0] is the lexically first hostname
	slices.Sort(hostNames)
	creator := certrotation.NewPeerRotation(
		func() []string {
			return hostNames
		},
		nil,
		nil,
		&user.DefaultInfo{
			Name: hostNames[0],
		},
	)

	rotator := certrotation.NewRotatedSelfSignedCertKeySecret(
		operatorclient.TargetNamespace,
		secretName,
		certName,
		certValidity.Validity,
		certValidity.RefreshAt,
		false,
		nil,
		certrotation.AdditionalAnnotations{
			JiraComponent:                    EtcdJiraComponentName,
			Description:                      description,
			AutoRegenerateAfterOfflineExpiry: "",
		},
		creator,
		pkiProvider,
		secretInformer,
		secretGetter,
		recorder,
	)

	return &rotator, nil
}

